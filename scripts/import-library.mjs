// (#431) Imports the exercise library from free-exercise-db at a pinned commit: text and tags only, no
// photos or media. Writes two content-hashed files to public/library/ (the index the list and search read,
// and the instructions the detail screen reads) and src/data/libraryFiles.ts naming them. Prints
// kept / linked / rejected counts and the gzip sizes.
//
//   node scripts/import-library.mjs                 fetch the pinned upstream file
//   node scripts/import-library.mjs --from <file>   read a local copy of dist/exercises.json instead
//
// TODO(#431): the second, MIT-licensed exercise source is off and has no code path here. If it is ever
// turned on, its full MIT notice must ship with it (CREDITS.md and Settings > About > Credits).
import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
import { EXERCISES } from '../src/data/exercises.ts';
import { SOURCE, SOURCE_FILE, buildLibrary, reportLines } from './library/transform.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const from = process.argv.indexOf('--from');
const upstream = from > 0
  ? JSON.parse(readFileSync(process.argv[from + 1], 'utf8'))
  : await (async () => {
    const response = await fetch(SOURCE_FILE);
    if (!response.ok) throw new Error(`${SOURCE_FILE} -> HTTP ${response.status}`);
    return response.json();
  })();
if (!Array.isArray(upstream)) throw new Error('Upstream file is not a list of exercises');

const media = JSON.parse(readFileSync(join(root, 'src/data/media.json'), 'utf8'));
const { rows, text, links, report } = buildLibrary(upstream, EXERCISES, media);

const dir = join(root, 'public/library');
mkdirSync(dir, { recursive: true });
for (const name of readdirSync(dir)) rmSync(join(dir, name));

const write = (kind, value) => {
  const body = JSON.stringify(value);
  const hash = createHash('sha256').update(body).digest('hex').slice(0, 10);
  const name = `${kind}.${hash}.json`;
  writeFileSync(join(dir, name), body);
  return { path: `/library/${name}`, bytes: Buffer.byteLength(body), gzip: gzipSync(body, { level: 9 }).length };
};
const source = { repo: SOURCE.repo, commit: SOURCE.commit };
const index = write('index', { version: 1, source, rows, links });
const instructions = write('text', { version: 1, source, text });

writeFileSync(join(root, 'src/data/libraryFiles.ts'), `// Generated by scripts/import-library.mjs (#431). Do not edit by hand: run the script again.
/** The exercise library's static files in public/library/, named by their content hash. */
export const LIBRARY_FILES = { index: '${index.path}', text: '${instructions.path}' } as const;
/** Where the text came from (CREDITS.md pins the same commit). */
export const LIBRARY_SOURCE = { repo: '${SOURCE.repo}', commit: '${SOURCE.commit}' } as const;
/** Rows in the index. */
export const LIBRARY_ROWS = ${rows.length};
`);

for (const line of reportLines(report)) console.log(line);
const kb = (n) => `${(n / 1024).toFixed(1)} KB`;
console.log(`index: ${index.path} ${kb(index.bytes)} raw, ${kb(index.gzip)} gzip (budget 40 KB)`);
console.log(`text:  ${instructions.path} ${kb(instructions.bytes)} raw, ${kb(instructions.gzip)} gzip (budget 260 KB)`);
if (index.gzip > 40 * 1024 || instructions.gzip > 260 * 1024) {
  console.error('Over the size budget.');
  process.exit(1);
}
